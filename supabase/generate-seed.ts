// Writes supabase/seed.sql from the demo's sample movies in web/app/movies.ts.
// Run from the repo root: node supabase/generate-seed.ts
import { writeFileSync } from "node:fs";
import { MOVIES } from "../web/app/movies.ts";

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;
const arr = (xs: readonly string[]) => `array[${xs.map(q).join(", ")}]::text[]`;

const movies = MOVIES.map((m) =>
  `  (${[q(m.id), q(m.title), m.year, m.runtime, q(m.rating), m.score, arr(m.genres), arr(m.moods),
    q(m.attention), m.intensity, q(m.synopsis), q(String(m.poster)), "true"].join(", ")})`,
).join(",\n");

const availability = MOVIES.flatMap((m) =>
  m.availability.map((a) => `  (${q(m.id)}, ${q(a.service)}, ${q(a.type)})`),
).join(",\n");

writeFileSync(
  new URL("./seed.sql", import.meta.url),
  `-- Generated by supabase/generate-seed.ts from web/app/movies.ts. Do not edit by hand.
-- Sample movies so the app has rows to read until CM-02 imports real ones.

insert into public.movies
  (id, title, year, runtime, rating, score, genres, moods, attention, intensity, synopsis, poster, is_sample)
values
${movies}
on conflict (id) do nothing;

insert into public.movie_availability (movie_id, service, type)
values
${availability}
on conflict do nothing;
`,
);
console.log(`Wrote ${MOVIES.length} movies to supabase/seed.sql`);
